$ErrorActionPreference = 'Stop'

# Measures which source lines the tests run, with coverlet.console pinned in .config/dotnet-tools.json.
# The tests are console programs, so coverlet instruments the built assemblies and runs each program.
# Results go to artifacts/coverage: a summary table on the console, and coverage.cobertura.xml with each line's hits.

$repositoryRoot = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$solution = Join-Path $repositoryRoot 'OyasumiGray.sln'
$output = Join-Path $repositoryRoot 'artifacts/coverage'

function Invoke-Step([string] $name, [scriptblock] $command) {
    Write-Host "==> $name"
    & $command
    if ($LASTEXITCODE -ne 0) { throw "$name failed with exit code $LASTEXITCODE" }
}

function Invoke-Coverage([string] $testProject, [string] $framework, [string[]] $formats, [string] $mergeWith) {
    $binary = Join-Path $repositoryRoot "tests/$testProject/bin/Release/$framework"
    $arguments = @('--targetargs', (Join-Path $binary "$testProject.dll"), '--output', (Join-Path $output '/'))
    foreach ($format in $formats) { $arguments += '--format', $format }
    if ($mergeWith) { $arguments += '--merge-with', $mergeWith }
    # The filters stay quoted literals here. PowerShell on Linux expands wildcards in arguments
    # that come from variables or arrays, which turned '[*.Tests]*' into folder names.
    # '**/obj/**' excludes code generated by the WinForms source generator.
    & dotnet tool run coverlet $binary --target dotnet --exclude '[*.Tests]*' --exclude-by-file '**/obj/**' @arguments
}

if (Test-Path $output) { Remove-Item $output -Recurse -Force }
New-Item -ItemType Directory -Path $output | Out-Null

Invoke-Step 'Restore tools' { dotnet tool restore }
Invoke-Step 'Build' { dotnet build $solution -c Release }

# The Windows tests need the Windows Desktop runtime, which is unavailable on Linux.
if ($env:OS -eq 'Windows_NT') {
    # Core first, then the Windows tests merged into the same result: they also run Core code.
    Invoke-Step 'Core tests with coverage' { Invoke-Coverage 'OyasumiGray.Core.Tests' 'net10.0' @('json') '' }
    Invoke-Step 'Windows tests with coverage' {
        Invoke-Coverage 'OyasumiGray.Windows.Tests' 'net10.0-windows' @('cobertura') (Join-Path $output 'coverage.json')
    }
}
else {
    Invoke-Step 'Core tests with coverage' { Invoke-Coverage 'OyasumiGray.Core.Tests' 'net10.0' @('cobertura') '' }
    Write-Warning 'Skipped Windows tests: they run only on Windows, so OyasumiGray.Windows is not measured.'
}

Write-Host "Coverage report: $(Join-Path $output 'coverage.cobertura.xml')"
